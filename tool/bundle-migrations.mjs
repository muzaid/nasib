// Concatenate the migrations into one file for the Supabase SQL editor.
//
//   node tool/bundle-migrations.mjs > setup.sql
//
// Eleven files pasted in order is eleven chances to paste one twice or
// skip one, and a half-applied schema fails later in a way that looks
// like an application bug. This is one paste, in order, wrapped in a
// transaction so a failure leaves nothing behind rather than leaving the
// database halfway.
//
// It is generated rather than committed: a checked-in copy drifts from
// the migrations the moment someone edits one, and the stale copy is the
// one that gets pasted.

import { readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const dir = join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const out = [
  "-- نصيب — the whole schema, in order, as one paste.",
  "-- Generated by tool/bundle-migrations.mjs. Do not edit; edit the",
  "-- migrations and regenerate.",
  "--",
  `-- ${files.length} migrations: ${files[0]} … ${files[files.length - 1]}`,
  "--",
  "-- Paste this into the Supabase SQL editor. It works on an empty",
  "-- project and on one that already has part of this schema: every",
  "-- statement in it either skips what is already there or replaces it,",
  "-- so pasting it again after a change applies only the difference.",
  "-- Your data is not touched — supabase/tests/rerun.sh is what keeps",
  "-- that true.",
  "--",
  "-- It is wrapped in a transaction: if anything fails, nothing is",
  "-- applied and the error names the statement, rather than leaving you",
  "-- with half a schema and no way to tell which half.",
  "--",
  "-- Do NOT run supabase/local/00_supabase_stubs.sql against this or any",
  "-- other hosted project. It fakes the auth schema for local testing and",
  "-- would overwrite the real one.",
  "",
  "begin;",
  "",
];

for (const file of files) {
  out.push(
    "-- " + "=".repeat(68),
    `-- ${file}`,
    "-- " + "=".repeat(68),
    "",
    readFileSync(join(dir, file), "utf8").trimEnd(),
    "",
  );
}

out.push("commit;", "");
process.stdout.write(out.join("\n"));
